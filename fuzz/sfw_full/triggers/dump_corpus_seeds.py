#!/usr/bin/env python3
# dump_corpus_seeds.py — write libFuzzer-corpus seeds matching each
# trigger reproducer in this directory.
#
# Each F*_*.c file in triggers/ is an executable reproducer that
# constructs a specific packet in C, then calls the libfuzzer-style
# entrypoint directly via main(). The two libfuzzer harnesses
# (../fuzz_translate_v{6_to_v4,4_to_v6}.c) consume the same byte
# sequence as their LLVMFuzzerTestOneInput input.
#
# This script reproduces the byte sequence each trigger constructs,
# byte-for-byte, and writes it as
#   ../corpus/<harness>/closed/<finding-id>.bin
# so audit-tools/regression-check.sh (and `cargo fuzz run <harness>
# corpus/<harness>/closed/`) replays them on every commit. Per
# audit-tools/PLAN.md item #2 ("regression-corpus discipline").
#
# Run once after a fix lands to refresh the closed/ corpus:
#   $ python3 triggers/dump_corpus_seeds.py
#
# The script is hand-derived from the trigger .c files; cross-check
# any update by hexdumping the .bin against the trigger's
# `xxd -i out/<trigger>` capture.

from pathlib import Path

HERE = Path(__file__).resolve().parent
CORPUS = HERE.parent / "corpus"

# (harness_name, finding_id, byte_string)
SEEDS = []


# F8 v6→v4: ICMPv6 echo-request, payload_length=0xFFFF, current_length=106.
# Mirrors triggers/F8_v6_to_v4.c. All bytes zero except the named fields.
def f8_v6_to_v4() -> bytes:
    pkt = bytearray(106)
    pkt[0:4] = b"\x60\x00\x00\x00"        # IPv6 v=6, TC=0, FL=0
    pkt[4:6] = b"\xff\xff"                # payload_length (BE) — attacker
    pkt[6] = 58                           # next_header = ICMP6
    pkt[7] = 64                           # hop_limit
    # bytes 8..39 = src/dst v6 addresses, zero
    pkt[40] = 128                         # ICMP6_echo_request
    # 41 code, 42-43 csum, all zero
    pkt[44:48] = b"\x12\x34\x56\x78"      # id+seq
    return bytes(pkt)


SEEDS.append(("fuzz_translate_v6_to_v4", "F8_v6_to_v4", f8_v6_to_v4()))


# F8 v4→v6: ICMPv4 echo-request, ip4->length=0xFFFF, 28-byte buffer.
# Mirrors triggers/F8_v4_to_v6.c. Headroom of 128 is supplied by the
# harness's fuzz_buffer_init call, not in the corpus seed.
def f8_v4_to_v6() -> bytes:
    pkt = bytearray(28)
    pkt[0] = 0x45                         # version 4, IHL 5
    pkt[1] = 0x00                         # TOS
    pkt[2:4] = b"\xff\xff"                # total_length (BE) — attacker
    pkt[8] = 64                           # TTL
    pkt[9] = 1                            # protocol = ICMP
    # 10-11 csum, 12-19 src/dst zero
    pkt[20] = 8                           # ICMP4_echo_request
    # 21 code, 22-23 csum
    pkt[24:28] = b"\x12\x34\x56\x78"      # id+seq
    return bytes(pkt)


SEEDS.append(("fuzz_translate_v4_to_v6", "F8_v4_to_v6", f8_v4_to_v6()))


