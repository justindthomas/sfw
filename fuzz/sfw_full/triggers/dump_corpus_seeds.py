def main() -> None:
    for harness, finding, payload in SEEDS:
        out_dir = CORPUS / harness / "closed"
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / f"{finding}.bin"
        out.write_bytes(payload)
        print(f"  {out.relative_to(HERE.parent)}  ({len(payload)} bytes)")


if __name__ == "__main__":
    main()
